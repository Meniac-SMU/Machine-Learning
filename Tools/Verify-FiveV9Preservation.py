"""Verify the approved v9 derivative against preserved v8 inputs and checkpoints."""
import hashlib
import json
from pathlib import Path
import zipfile

ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'Logs/Manager5v5/keeper-accel12-v9-20261016'
def read(p):return json.loads(p.read_text(encoding='utf-8-sig'))
def sha(p):
    h=hashlib.sha256()
    with p.open('rb') as f:
        for part in iter(lambda:f.read(4*1024*1024),b''):h.update(part)
    return h.hexdigest()

def main():
    manifest=read(ROOT/'docs/soccer/rebuild-5v5/p9-frozen-v8-manifest.json')
    approved=read(OUT/'authorized-changes.json')
    scene='Assets/_Soccer/Manager5v5/Scenes/FiveLearning.unity'
    expected={x['path'] for x in approved}|{scene}
    changed=[];preserved=0;builds=0
    for item in manifest['inputs']:
        path=ROOT/item['path'];assert path.is_file(),item['path']
        if sha(path).lower()!=item['sha256'].lower():changed.append(item['path'])
        else:
            preserved+=1
            if item['path'].startswith('Builds/'):builds+=1
    assert set(changed)==expected,changed
    with zipfile.ZipFile(OUT/'source-before.zip') as z:
        stored=read_zip_manifest=json.loads(z.read('source-manifest.json').decode('utf-8-sig'))
        for item in stored:assert hashlib.sha256(z.read(item['path'])).hexdigest().lower()==item['sha256'].lower()
        for item in approved:
            assert hashlib.sha256(z.read(item['path'])).hexdigest()==item['beforeSha']
            assert sha(ROOT/item['path'])==item['afterSha']
        assert hashlib.sha256(z.read(scene)).hexdigest()==next(x['sha256'] for x in manifest['inputs'] if x['path']==scene)
    assert sha(ROOT/'ProjectSettings/ProjectSettings.asset')==sha(OUT/'ProjectSettings-before.asset')
    old=ROOT/'Logs/Manager5v5/p9-frozen-v8-20261015/MNG5_V5-20261016-r001'
    done=read(old/'completion-verification-2400.json');assert done['passed'] and done['targetSteps']==2400000
    registry=read(old/'model-registry.json');assert registry['champion'] is None
    model=ROOT/'results/Manager5v5/MNG5_V5-20261016-r001/MNG5_Manager_v5'
    checked=[]
    for c in done['checkpoints']:
        step=c['step']
        for name,key in [(f'MNG5_Manager_v5-{step}.onnx','onnxSha256'),(f'MNG5_Manager_v5-{step}.pt','ptSha256'),(f'five-pool-{step}.pt','poolSha256')]:
            p=model/name;assert sha(p)==c[key],name
            checked.append(dict(path=str(p.relative_to(ROOT)),sha256=c[key]))
    assert len(checked)==39
    receipt=dict(passed=True,frozenInputs=len(manifest['inputs']),preservedFrozenInputs=preserved,preservedBuildFiles=builds,
        changedCurrentInputs=changed,approvedRuntimeFiles=approved,generatedScene=scene,
        note='FiveLearning.unity was regenerated by the unchanged builder; the original scene and all original source entries remain in source-before.zip. Current v9 is intentionally distinct from frozen v8.',
        sourceArchiveEntriesVerified=len(stored),projectSettingsRestored=True,checkpointsPreserved=13,checkpointFilesVerified=checked,
        targetSteps=2400000,champion=None,completionRecordSha=sha(old/'completion-verification-2400.json'),registrySha=sha(old/'model-registry.json'))
    (OUT/'preservation-verification.json').write_text(json.dumps(receipt,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in receipt.items() if k not in ('approvedRuntimeFiles','checkpointFilesVerified')},ensure_ascii=False))

if __name__=='__main__':main()
